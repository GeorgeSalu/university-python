# isupper() = verifica se todos os caracteres alfabéticos de uma string estão em letras maiúsculas. Ele retorna True se a
# condição for atendida e False caso contrário. Caracteres especiais e números são ignorados na validação

texto = "PYTHON É INCRÍVEL"
print(texto.isupper())

texto2 = "Python é legal"
print(texto2.isupper())

texto3 = "PYTHON 3!"
print(texto3.isupper())