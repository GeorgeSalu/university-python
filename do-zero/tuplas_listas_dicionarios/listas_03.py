mochila = ['laptop', 'smartphone', 'power bank','carregadores e cabos']

print(mochila)
# append() adiciona no final da lista
mochila.append('oculos')
# insert() adiciona em uma posição definida
mochila.insert(1, 'canivete')
print(mochila)
# remove() remove da lista
mochila.remove('oculos')
print(mochila)